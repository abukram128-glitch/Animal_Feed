import streamlit as st
import requests

# إعدادات الصفحة
st.set_page_config(page_title="Smart Feed Formulation", layout="centered")

st.title("🌾 النظام الذكي لتركيب وابتكار الأعلاف بأقل تكلفة")
st.write("هذا التطبيق يقوم بحساب التوليفة المثالية للأعلاف باستخدام البرمجة الخطية وتلبية الاحتياجات الغذائية الدقيقة.")

# 1. قائمة الأنواع المتوفرة بناءً على ملف البيانات في السيرفر
animal_options = {
    "المجترات - أبقار تسمين": "المجترات - أبقار تسمين",
    "المجترات - أبقار ألبان": "المجترات - أبقار ألبان",
    "المجترات - أغنام تسمين": "المجترات - أغنام تسمين",
    "المجترات - ماعز تسمين": "المجترات - ماعز تسمين",
    "الدواجن - بادي (لاحم)": "الدواجن - بادي (لاحم)",
    "الدواجن - نامي (لاحم)": "الدواجن - نامي (لاحم)",
    "الدواجن - ناهي (لاحم)": "الدواجن - ناهي (لاحم)",
    "الدواجن - بياض (إنتاج بيض)": "الدواجن - بياض (إنتاج بيض)",
    "الخيول - خيول - رياضة": "الخيول - خيول - رياضة",
    "الخيول - خيول - أمهار": "الخيول - خيول - أمهار",
    "الخيول - خيول - فرسات": "الخيول - خيول - فرسات"
}

selected_animal = st.selectbox("🎯 اختر نوع الحيوان أو المرحلة الإنتاجية:", list(animal_options.keys()))

st.write("---")
st.subheader("💰 أدخل أسعار السوق الحالية للخامات (لكل 1 كيلو جرام):")

# قائمة الخامات ليتيح للمستخدم إدخال أسعارها الحالية
ingredients_list = [
    "الذرة الصفراء", "الذرة البيضاء", "كسب فول الصويا 44%", "كسب فول الصويا 48%", 
    "كسب عباد الشمس 36%", "مركزات دواجن لاحم (5%)", "مركزات دواجن بياض (10%)", 
    "البرسيم الجاف (الدريس)", "النخالة (الردة)", "الشعير المطحون", "الشوفان", 
    "الحجر الجيري (بودرة بلاط)", "فوسفات ثنائي الكالسيوم (DCP)", "ملح الطعام", 
    "مضاد سموم فطرية وبيولوجية", "بريمكس مجترات (تسمين/ألبان)", 
    "بريمكس دواجن (لاحم/بياض)", "بريمكس خيول (مركز)"
]

# تجميع الأسعار من المستخدم في قاموس
user_prices = {}
col1, col2 = st.columns(2)

for idx, ing_name in enumerate(ingredients_list):
    # توزيع الخانات على عمودين لتنظيم الواجهة
    if idx % 2 == 0:
        with col1:
            user_prices[ing_name] = st.number_input(f"سعر {ing_name}:", min_value=0.0, value=10.0, step=0.5, key=f"ing_{idx}")
    else:
        with col2:
            user_prices[ing_name] = st.number_input(f"سعر {ing_name}:", min_value=0.0, value=10.0, step=0.5, key=f"ing_{idx}")

st.write("---")

# 2. زر تشغيل الحسبة والإرسال للسيرفر
if st.button("🚀 احسب التركيبة العلفية الأقل تكلفة الآن", use_container_width=True):
    
    # تجهيز البيانات (Payload) لإرسالها في الخلفية
    payload = {
        "animal_key": selected_animal,
        "prices": user_prices
    }
    
    # رابط الـ API الخاص بك على السيرفر الآمن
    URL = "https://Abdalgadr.pythonanywhere.com/calculate"
    
    with st.spinner("جاري الاتصال بالخزنة السحابية وحساب المعادلة برمجياً..."):
        try:
            # إرسال الطلب عبر بروتوكول POST الآمن
            response = requests.post(URL, json=payload)
            
            if response.status_code == 200:
                result = response.json()
                
                if result["status"] == "success":
                    st.balloons() # تأثير احتفالي عند النجاح
                    st.success(f"✅ تمت العملية بنجاح! التكلفة الإجمالية التقريبية لـ 100 كيلو جرام هي: {result['total_cost_per_100kg']} وحدة نقدية.")
                    
                    st.write("### 📊 نسب توزيع الخامات في الخلطة (مجموعها 100%):")
                    
                    # عرض نسب المكونات التي اختارتها البرمجة الخطية فقط
                    for feed_name, percentage in result["proportions"].items():
                        st.info(f"🔹 **{feed_name}:** بنسبة **{percentage}%** (أي {percentage} كجم لكل 100 كجم علف)")
                else:
                    st.warning(f"⚠️ تنبيه من السيرفر: {result['message']}")
            else:
                st.error("❌ فشل السيرفر في معالجة البيانات، تأكد من تحديث ملف main.py بشكل صحيح.")
                
        except Exception as e:
            st.error(f"🌐 عذراً، تعذر الاتصال بالسيرفر. تأكد من اتصال الإنترنت أو أن السيرفر يعمل. (الخطأ: {e})")
