            sq = st.text_input("🔍 بحث:", placeholder="ذرة، صويا...", key="ing_search")

            selected = []
            default_set = get_default_selections(animal_choice, production_type, requirement)

            for cat_name, items in BIG_FEEDS_LIBRARY.items():
                filt = {k: v for k, v in items.items() if sq.lower() in k.lower()} if sq else items
                if not filt: continue
                expanded = ("الحبوب" in cat_name or "الأكساب" in cat_name)
                with st.expander(f"📁 {cat_name} ({len(filt)})", expanded=expanded):
                    sc = st.columns(3)
                    for idx, ing_name in enumerate(filt.keys()):
                        with sc[idx % 3]:
                            if st.checkbox(ing_name, value=ing_name in default_set, key=f"pick_{animal_choice}_{ing_name}"):
                                selected.append(ing_name)

            st.markdown("### 💰 أسعار المواد")
            prices_dict = {}
            if selected:
                pcols = st.columns(min(3, len(selected)))
                for idx, ing in enumerate(selected):
                    with pcols[idx % 3]:
                        default_price = float(_get_ingredient_lookup().get(ing, {}).get("price", 350.0))
                        prices_dict[ing] = st.number_input(f"💵 {ing} ($/طن)", min_value=5.0, value=default_price, step=10.0, key=f"p_sel_{animal_choice}_{ing}")

            st.success(f"✅ المختارة: **{len(selected)}** مادة + **{len(baseline_preview)}** ثابت إلزامي")

            run = st.button("🚀 تشغيل المحرك الآمن", type="primary", use_container_width=True, key="run_btn")

            if run:
                if len(selected) < 2:
                    st.error("⚠️ اختر مادتين على الأقل")
                else:
                    custom_std = requirement_to_standard(requirement)
                    with st.spinner(f"⏳ التركيب الآمن ({basis_code})..."):
                        multi = formulate_multiple_options(selected, prices_dict, custom_std,
                                                              standard_key=std_key_global, basis=basis_code,
                                                              min_quality=70.0, animal_type=animal_choice,
                                                              production_type=production_type,
                                                              requirement=requirement, n_options=5)
                    if multi["success"] and multi["options"]:
                        st.session_state["multi_options"] = multi["options"]
                        result = multi["options"][0]
                        st.session_state["last_formulation_result"] = result
                        st.session_state["last_formulation_context"] = {
                            "animal_choice": animal_choice, "requirement_name": requirement.name_ar,
                            "basis_label": basis_code, "requirement": requirement,
                            "custom_standard": custom_std, "city": "—", "local_rate": 1.0,
                            "local_sym": "USD", "requester_name": requester_name,
                            "std_key_global": std_key_global, "animal_type": animal_choice,
                            "production_type": production_type}
