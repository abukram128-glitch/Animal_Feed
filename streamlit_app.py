def detect_harmful_mix(formula, animal_type, production_type="", requirement=None, targets=None):
    warns = []
    actual = compute_formula_nutrients(formula)
    def add(level, title, detail, source, action):
        warns.append({"level": level, "title": title, "detail": detail, "source": source, "action": action})
    is_poultry = animal_type in ("دواجن", "سمان")
    is_monogastric = animal_type in ("دواجن", "سمان", "خيول", "أسماك", "أرانب")
    is_ruminant = animal_type in ("أبقار", "أغنام", "ماعز", "إبل")
    for ing, pct in formula.items():
        hz = _get_hazard_info(ing)
        if not hz or pct <= 0.01: continue
        limit = _hazard_limit_for(ing, animal_type, production_type)
        if limit is not None and pct > limit + 0.01:
            if limit == 0:
                add("critical", f"🚨 {ing} — {hz['hazard']} ممنوع لـ{animal_type}",
                    f"{pct:.2f}% > 0%", hz["source"], hz["action"])
            elif pct > limit * 1.3:
                add("critical", f"🚨 {ing} — تجاوز {hz['hazard']}",
                    f"{pct:.2f}% > {limit:.2f}%", hz["source"], hz["action"])
            else:
                add("warning", f"⚠️ {ing} — قرب حد {hz['hazard']}",
                    f"{pct:.2f}% > {limit:.2f}%", hz["source"], hz["action"])
    salt = formula.get("ملح الطعام", 0)
    if salt > 1.0:
        add("critical", "🚨 ملح زائد", f"{salt:.2f}% > 1%", "NRC 2001", "اخفض إلى 0.3-0.5%")
    elif salt > 0.6:
        add("warning", "⚠️ ملح مرتفع", f"{salt:.2f}%", "NRC 2001", "اخفض")
    ca, p = actual.get("Ca", 0), actual.get("P", 0)
    if p > 0:
        r = ca / p
        lo, hi = (1.5, 2.2) if is_poultry else (1.5, 2.0)
        if r < 1.0: add("critical", "🚨 Ca:P < 1.0", f"{r:.2f}", "NRC", "أضف حجر جيري")
        elif r < lo: add("warning", "⚠️ Ca:P منخفض", f"{r:.2f} < {lo}", "NRC", "أضف حجر جيري")
        elif r > hi * 1.5: add("warning", "⚠️ Ca:P مرتفع", f"{r:.2f}", "NRC", "أضف فوسفات")
    return warns


