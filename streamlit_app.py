def _hazard_limit_for(ingredient, animal_type, production_type=""):
    hz = _get_hazard_info(ingredient)
    if not hz: return None
    limits = hz.get("limits_by_class", {})
    if animal_type in ("دواجن", "سمان"): key = "poultry"
    elif animal_type == "خيول": key = "horses"
    elif animal_type == "أسماك": key = "fish"
    elif animal_type in ("أبقار", "أغنام", "ماعز", "إبل"): key = "ruminant"
    else: key = "monogastric"
    is_young = any(k in (production_type or "") for k in ("بادي", "زريعة", "جديان", "حملان_تيد", "نمو_أمهار"))
    if is_young and "young" in limits: return limits["young"]
    return limits.get(key)


