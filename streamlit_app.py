def generate_alert_wav(pattern="critical"):
    sr = 22050
    if pattern == "critical":
        seq = [(880, .18), (0, .06), (660, .22), (0, .05), (440, .28)]; vol = 28000
    elif pattern == "warning":
        seq = [(520, .30), (0, .10), (420, .30)]; vol = 22000
    else:
        seq = [(660, .10), (0, .04), (880, .12), (0, .04), (1100, .15)]; vol = 18000
    buf = io.BytesIO()
    with wave.open(buf, 'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(sr)
        for freq, dur in seq:
            n = int(dur * sr)
            for i in range(n):
                if freq == 0: val = 0
                else:
                    t = i / sr
                    env = min(t * 25, (dur - t) * 25, 1.0)
                    val = int(vol * env * math.sin(2 * math.pi * freq * t))
                w.writeframes(struct.pack('<h', max(-32767, min(32767, val))))
    buf.seek(0)
    return buf.getvalue()

def play_alert(pattern="critical"):
    try: st.audio(generate_alert_wav(pattern), format="audio/wav", autoplay=True)
    except Exception: pass


