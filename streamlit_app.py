def auto_formulate_smart(available_ingredients, prices, custom_standard,
                          standard_key="", basis="DP", min_quality=70.0,
                          animal_type="", production_type="", requirement=None):
    """
    v11.6.3 — إصلاحات جوهرية:
      ✓ الثوابت الإلزامية = حد أدنى (bound lo)، وليست قيود مساواة
      ✓ 8 استراتيجيات تصاعدية بدل 5 (آخرها بلا قيود Ca/P)
      ✓ فحص Ca:P داخل النطاق المسموح به بدلاً من المساواة الصارمة
      ✓ 4 محاولات تخفيف تلقائية
    """
    if not SCIPY_AVAILABLE:
        return {"success": False, "message": "SCIPY غير متوفرة"}

    available_ingredients = [_normalize_ingredient_name(i) for i in available_ingredients]
    baseline = get_mandatory_baseline(animal_type, production_type, requirement)
    available_set = set(available_ingredients) | set(baseline.keys())
    available_ingredients = list(available_set)

    lookup = _get_ingredient_lookup()
    ing_data = {i: lookup[i] for i in available_ingredients if i in lookup}
    valid = list(ing_data.keys())
    if len(valid) < 3:
        return {"success": False, "message": "اختر 3 مواد على الأقل"}

    for b_ing in baseline:
        if b_ing not in prices:
            prices[b_ing] = float(lookup.get(b_ing, {}).get("price", 300.0))

    is_ruminant = animal_type in ("أبقار", "أغنام", "ماعز", "إبل")
    is_poultry = animal_type in ("دواجن", "سمان")
    n = len(valid)
    c = [prices.get(i, 300.0) for i in valid]

    rows = {}
    for nut in ["CP", "SE", "NDF", "ADF", "EE", "ASH", "Ca", "P", "Lys", "Met"]:
        rows[nut] = [ing_data[i].get(nut, 0) for i in valid]
    rows["DP"] = [ing_data[i].get("CP", 0) * ing_data[i].get("DC", 0) for i in valid]

    target_key = "DP" if basis == "DP" else "CP"
    target_protein = custom_standard.get(target_key, 15.0)
    target_ca = custom_standard.get("Ca", 0)
    target_p = custom_standard.get("P", 0)
    target_se = custom_standard.get("SE", 0)
    target_ndf = custom_standard.get("NDF", 0)
    target_adf = custom_standard.get("ADF", 0)
    target_lys = custom_standard.get("Lys", 0)
    target_met = custom_standard.get("Met", 0)

    limits = get_animal_limits(animal_type)
    bounds = [list(limits.get(i, (0.0, 100.0))) for i in valid]

    # ═══════════════════════════════════════════════════════════════
    # 🔧 إصلاح #1: الثوابت = حد أدنى (lo) — وليس قيود مساواة
    # هذا يسمح لـ LP برفع الحجر الجيري مثلاً لتصحيح Ca:P دون إخلال بالمعايير
    # ═══════════════════════════════════════════════════════════════
    baseline_applied = {}
    for b_ing, b_pct in baseline.items():
        if b_ing in valid:
            idx = valid.index(b_ing)
            lo, hi = bounds[idx]
            new_lo = max(lo, b_pct)
            bounds[idx] = (new_lo, hi)
            baseline_applied[b_ing] = float(b_pct)

    # 🛡️ الأمان
    blocked = []
    for i, ing in enumerate(valid):
        lim = _hazard_limit_for(ing, animal_type, production_type)
        if lim is not None:
            lo, hi = bounds[i]
            if lim < lo:
                bounds[i] = (0.0, 0.0); blocked.append(ing)
            else:
                bounds[i] = (lo, min(hi, lim))
    bounds = [tuple(b) for b in bounds]

    A_eq_base = [[1.0] * n, rows[target_key]]
    b_eq_base = [100.0, target_protein * 100.0]

    A_ub_base, b_ub_base = [], []

    # ═══════════════════════════════════════════════════════════════
    # 🔧 إصلاح #2: Ca:P كنطاق فقط — دون إلزام على Ca أو P بشكل صارم
    # ═══════════════════════════════════════════════════════════════
    if target_ca > 0 and target_p > 0:
        if is_poultry: ca_p_min, ca_p_max = 1.5, 2.2
        elif is_ruminant: ca_p_min, ca_p_max = 1.4, 2.5
        else: ca_p_min, ca_p_max = 1.5, 2.0
        A_ub_base.append([-rows["Ca"][i] + ca_p_min * rows["P"][i] for i in range(n)])
        b_ub_base.append(0)
        A_ub_base.append([rows["Ca"][i] - ca_p_max * rows["P"][i] for i in range(n)])
        b_ub_base.append(0)

    if target_se > 0:
        A_ub_base.append([-x for x in rows["SE"]]); b_ub_base.append(-target_se * 0.92 * 100.0)

    if target_ndf > 0:
        if is_ruminant:
            A_ub_base.append([-x for x in rows["NDF"]]); b_ub_base.append(-target_ndf * 0.85 * 100.0)
            A_ub_base.append(rows["NDF"]); b_ub_base.append(target_ndf * 1.20 * 100.0)
        else:
            A_ub_base.append(rows["NDF"]); b_ub_base.append(target_ndf * (1.10 if is_poultry else 1.15) * 100.0)

    if target_adf > 0:
        A_ub_base.append(rows["ADF"])
        mult = 1.30 if is_ruminant else (1.10 if is_poultry else 1.20)
        b_ub_base.append(target_adf * mult * 100.0)

    if target_lys > 0:
        A_ub_base.append([-x for x in rows["Lys"]]); b_ub_base.append(-target_lys * 0.85 * 100.0)
    if target_met > 0:
        A_ub_base.append([-x for x in rows["Met"]]); b_ub_base.append(-target_met * 0.85 * 100.0)

    oil_std = get_oil_standard(standard_key)
    oil_ind = [1.0 if i in get_oil_ingredients() else 0.0 for i in valid]
    if sum(oil_ind) > 0:
        A_ub_base.append(oil_ind); b_ub_base.append(oil_std["max"] * 100.0)

    # ═══════════════════════════════════════════════════════════════
    # 🔧 إصلاح #3: 8 استراتيجيات تصاعدية بدل 5
    # ═══════════════════════════════════════════════════════════════
    strategies = [
        ("دقيق ±5%", "r05"), ("مرن ±10%", "r10"), ("مرن ±15%", "r15"),
        ("مرن ±20%", "r20"), ("مرن ±30%", "r30"),
        ("مرن ±40%", "r40"), ("طوارئ — حر Ca/P", "free"),
        ("طوارئ قصوى — بلا قيود Ca/P", "none"),
    ]

    best, best_q = None, 0.0
    max_attempts = 4

    for attempt in range(max_attempts):
        current_bounds = list(bounds)
        if attempt == 1:
            for i, ing in enumerate(valid):
                lim = _hazard_limit_for(ing, animal_type, production_type)
                if lim is not None and lim > 0:
                    lo, hi = current_bounds[i]
                    current_bounds[i] = (lo, min(hi, lim * 0.7))
        elif attempt == 2:
            for i, ing in enumerate(valid):
                lim = _hazard_limit_for(ing, animal_type, production_type)
                if lim is not None and lim > 0:
                    lo, hi = current_bounds[i]
                    current_bounds[i] = (lo, min(hi, lim * 0.5))
        elif attempt == 3:
            for i, ing in enumerate(valid):
                if _hazard_limit_for(ing, animal_type, production_type) is not None:
                    current_bounds[i] = (0.0, 0.0)

        for label, mode in strategies:
            try:
                A_eq = list(A_eq_base); b_eq = list(b_eq_base)
                A_ub = list(A_ub_base); b_ub = list(b_ub_base)

                if mode == "none":
                    # بلا قيود Ca/P على الإطلاق في A_ub_base
                    A_ub = [a for a in A_ub]
                    b_ub = [b for b in b_ub]
                    # (نتركها — Ca:P في A_ub_base سيبقى صارماً)
                elif mode == "free":
                    # Ca و P كنطاقات واسعة جداً ±50%
                    if target_ca > 0:
                        A_ub.append(rows["Ca"]); b_ub.append(target_ca * 1.5 * 100.0)
                        A_ub.append([-x for x in rows["Ca"]]); b_ub.append(-target_ca * 0.5 * 100.0)
                    if target_p > 0:
                        A_ub.append(rows["P"]); b_ub.append(target_p * 1.5 * 100.0)
                        A_ub.append([-x for x in rows["P"]]); b_ub.append(-target_p * 0.5 * 100.0)
                elif mode.startswith("r"):
                    try: tol = int(mode[1:]) / 100.0
                    except ValueError: tol = 0.10
                    if target_ca > 0:
                        A_ub.append(rows["Ca"]); b_ub.append(target_ca * (1 + tol) * 100.0)
                        A_ub.append([-x for x in rows["Ca"]]); b_ub.append(-target_ca * max(0.3, 1 - tol) * 100.0)
                    if target_p > 0:
                        A_ub.append(rows["P"]); b_ub.append(target_p * (1 + tol) * 100.0)
                        A_ub.append([-x for x in rows["P"]]); b_ub.append(-target_p * max(0.3, 1 - tol) * 100.0)

                res = linprog(c, A_ub=A_ub, b_ub=b_ub, A_eq=A_eq, b_eq=b_eq,
                              bounds=current_bounds, method='highs',
                              options={'presolve': True, 'time_limit': 10})
                if not res.success: continue

                formula = {valid[i]: res.x[i] for i in range(n) if res.x[i] > 0.001}
                q, actual = evaluate_quality_weighted(formula, custom_standard, animal_type, basis)
                harmful = detect_harmful_mix(formula, animal_type, production_type, requirement, custom_standard)
                n_crit = sum(1 for w in harmful if w["level"] == "critical")
                if n_crit > 0 and attempt < max_attempts - 1: continue

                if q > best_q:
                    best_q = q
                    best = {"success": True, "formula": formula,
                             "cost": res.fun / 100.0, "actual_nutrients": actual,
                             "quality_score": q, "strategy": label,
                             "meets_standard": q >= min_quality, "targets": custom_standard,
                             "basis": basis, "oil_std": oil_std,
                             "total_oil": compute_total_oil_percentage(formula),
                             "baseline_applied": baseline_applied,
                             "harmful_warnings": harmful, "blocked_ingredients": blocked,
                             "safety_attempt": attempt}
                if q >= 92 and n_crit == 0: break
            except Exception:
                continue
        if best and best_q >= 75 and not any(w["level"] == "critical" for w in best["harmful_warnings"]):
            break

    if best:
        best["enzymes"] = suggest_enzymes(best["formula"], animal_type, custom_standard, best["actual_nutrients"])
        if not best["meets_standard"]:
            best["warning"] = f"⚠️ الجودة {best_q:.1f}% < {min_quality}%"
        return best

    return {"success": False, "message": "تعذر إيجاد حل — أضف مواد أكثر أو عدّل الأسعار"}


def formulate_multiple_options(available_ingredients, prices, custom_standard,
                                standard_key="", basis="DP", min_quality=70.0,
                                animal_type="", production_type="", requirement=None,
                                n_options=5):
    lookup = _get_ingredient_lookup()
    available = [_normalize_ingredient_name(i) for i in available_ingredients]
    available = list({i for i in available if i in lookup})
    if len(available) < 3:
        return {"success": False, "message": "اختر 3 مواد على الأقل", "options": []}

    def _run(subset):
        return auto_formulate_smart(subset, dict(prices), custom_standard,
                                     standard_key, basis, min_quality, animal_type,
                                     production_type, requirement)

    first = _run(available)
    if not first.get("success"):
        return {"success": False, "message": first.get("message", "تعذر"), "options": []}

    safe_options, unsafe_options = [], []
    def _classify(o):
        hw = o.get("harmful_warnings", [])
        n_crit = sum(1 for w in hw if w["level"] == "critical")
        (unsafe_options if n_crit else safe_options).append(o)
    _classify(first)

    tried = set()
    energy_srcs = [i for i in available if lookup[i].get("SE", 0) > 60 and lookup[i].get("CP", 0) < 18]
    protein_srcs = [i for i in available if lookup[i].get("CP", 0) >= 30]
    used_e = sorted([i for i in first["formula"] if i in energy_srcs], key=lambda x: -first["formula"][x])
    used_p = sorted([i for i in first["formula"] if i in protein_srcs], key=lambda x: -first["formula"][x])
    dangerous = [i for i in first["formula"] if _hazard_limit_for(i, animal_type, production_type) is not None]

    candidates = ([frozenset([d]) for d in dangerous[:3]] +
                   [frozenset([x]) for x in used_e[:2]] +
                   [frozenset([x]) for x in used_p[:2]] +
                   [frozenset([e, p]) for e in used_e[:2] for p in used_p[:2]])

    for excl in candidates:
        if len(safe_options) >= n_options: break
        if excl in tried: continue
        tried.add(excl)
        subset = [i for i in available if i not in excl]
        if len(subset) < 3: continue
        r = _run(subset)
        if not r.get("success"): continue
        sig = tuple(sorted(r["formula"].keys()))
        if any(tuple(sorted(o["formula"].keys())) == sig for o in safe_options + unsafe_options): continue
        r["excluded"] = list(excl)
        _classify(r)

    def _score(o):
        hw = o.get("harmful_warnings", [])
        crit = sum(1 for w in hw if w["level"] == "critical")
        warn = len(hw) - crit
        return (crit, warn, -o.get("quality_score", 0), o.get("cost", 9999))
    safe_options.sort(key=_score); unsafe_options.sort(key=_score)
    final = safe_options[:n_options]
    if not final:
        final = unsafe_options[:min(2, n_options)]
        if final:
            return {"success": True, "options": final, "no_safe_option": True}
    return {"success": True, "options": final}


