def safe_section(func):
    @wraps(func)
    def wrapper(*a, **k):
        try:
            return func(*a, **k)
        except Exception as e:
            st.error(f"⚠️ خطأ: {type(e).__name__}")
            with st.expander("🔍 التفاصيل"):
                st.code(traceback.format_exc())
            st.info(f"💡 F5 للتحقق | {OWNER_EMAIL}")
    return wrapper


